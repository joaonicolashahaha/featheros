#!/usr/bin/env python3
"""Generate the FeatherOS-Light / FeatherOS-Dark Openbox themes (original).

Traffic-light title buttons: Openbox 3.6 only takes 1-bit XBM bitmaps, but
colours each button separately, so a filled circle per button gives the
red/yellow/green look. On hover the glyph (x, -, +) is cut out of the circle.

    python3 artwork/make-openbox-theme.py
"""
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "archiso", "airootfs",
                    "usr", "share", "themes")
N = 12  # button bitmap size (px)


def circle():
    c = (N - 1) / 2
    return [[(x - c) ** 2 + (y - c) ** 2 <= (N / 2) ** 2 - 0.5
             for x in range(N)] for y in range(N)]


def cut(bits, points):
    for x, y in points:
        bits[y][x] = False
    return bits


def glyph(kind):
    lo, hi = 3, N - 4
    if kind == "x":
        return [(i, i) for i in range(lo, hi + 1)] + \
               [(i, N - 1 - i) for i in range(lo, hi + 1)]
    if kind == "-":
        return [(i, y) for i in range(lo, hi + 1) for y in (5, 6)]
    if kind == "+":
        return [(i, y) for i in range(lo, hi + 1) for y in (5, 6)] + \
               [(x, i) for i in range(lo, hi + 1) for x in (5, 6)]
    return []


def xbm(name, bits):
    data = []
    for row in bits:
        for byte in range(0, N, 8):
            v = 0
            for bit in range(8):
                if byte + bit < N and row[byte + bit]:
                    v |= 1 << bit
            data.append(f"0x{v:02x}")
    return (f"#define {name}_width {N}\n#define {name}_height {N}\n"
            f"static unsigned char {name}_bits[] = {{\n   "
            + ", ".join(data) + " };\n")


BUTTONS = {  # file -> hover glyph
    "close": "x", "iconify": "-", "max": "+", "max_toggled": "+",
    "desk": "", "desk_toggled": "", "shade": "", "shade_toggled": "",
}

PALETTES = {
    "Light": dict(title="#ececec", title_i="#f6f6f6", border="#c4c4c4",
                  border_i="#d6d6d6", text="#3c3c3c", text_i="#acacac",
                  btn_i="#d0d0d0", menu_bg="#f6f6f6", menu_text="#1e1e1e",
                  menu_dis="#a0a0a0", sep="#d8d8d8"),
    "Dark": dict(title="#2e2e30", title_i="#262628", border="#141414",
                 border_i="#1c1c1c", text="#dcdcdc", text_i="#7a7a7a",
                 btn_i="#4c4c4e", menu_bg="#2b2b2d", menu_text="#e8e8e8",
                 menu_dis="#707070", sep="#3c3c3e"),
}
RED, YELLOW, GREEN, BLUE = "#ff5f57", "#febc2e", "#28c840", "#3a82f7"
DARKER = {RED: "#c9473f", YELLOW: "#c99520", GREEN: "#1f9a32"}

THEMERC = """\
# FeatherOS-{name} Openbox theme. Generated by artwork/make-openbox-theme.py.
border.width: 1
padding.width: 7
padding.height: 5
window.handle.width: 0
window.client.padding.width: 0
window.client.padding.height: 0
window.label.text.justify: center

window.active.border.color: {border}
window.inactive.border.color: {border_i}
window.active.client.color: {title}
window.inactive.client.color: {title_i}

window.active.title.bg: flat solid
window.active.title.bg.color: {title}
window.inactive.title.bg: flat solid
window.inactive.title.bg.color: {title_i}
window.active.handle.bg: flat solid
window.active.handle.bg.color: {title}
window.inactive.handle.bg: flat solid
window.inactive.handle.bg.color: {title_i}
window.active.grip.bg: flat solid
window.active.grip.bg.color: {title}
window.inactive.grip.bg: flat solid
window.inactive.grip.bg.color: {title_i}

window.active.label.bg: parentrelative
window.inactive.label.bg: parentrelative
window.active.label.text.color: {text}
window.inactive.label.text.color: {text_i}

window.*.button.*.bg: parentrelative
window.active.button.*.image.color: {text}
window.inactive.button.*.image.color: {btn_i}

window.active.button.close.unpressed.image.color: {red}
window.active.button.close.hover.image.color: {red}
window.active.button.close.pressed.image.color: {red_d}
window.active.button.iconify.unpressed.image.color: {yellow}
window.active.button.iconify.hover.image.color: {yellow}
window.active.button.iconify.pressed.image.color: {yellow_d}
window.active.button.max.unpressed.image.color: {green}
window.active.button.max.hover.image.color: {green}
window.active.button.max.pressed.image.color: {green_d}
window.active.button.max.toggled.unpressed.image.color: {green}
window.active.button.max.toggled.hover.image.color: {green}
window.active.button.max.toggled.pressed.image.color: {green_d}
window.inactive.button.close.hover.image.color: {red}
window.inactive.button.iconify.hover.image.color: {yellow}
window.inactive.button.max.hover.image.color: {green}
window.inactive.button.max.toggled.hover.image.color: {green}

menu.border.width: 1
menu.border.color: {border}
menu.separator.color: {sep}
menu.separator.padding.width: 6
menu.separator.padding.height: 3
menu.title.bg: flat solid
menu.title.bg.color: {menu_bg}
menu.title.text.color: {text_i}
menu.title.text.justify: left
menu.items.bg: flat solid
menu.items.bg.color: {menu_bg}
menu.items.text.color: {menu_text}
menu.items.disabled.text.color: {menu_dis}
menu.items.active.bg: flat solid
menu.items.active.bg.color: {blue}
menu.items.active.text.color: #ffffff
menu.items.active.disabled.text.color: {menu_dis}
menu.overlap.x: -2

osd.border.width: 1
osd.border.color: {border}
osd.bg: flat solid
osd.bg.color: {menu_bg}
osd.label.bg: flat solid
osd.label.bg.color: {menu_bg}
osd.label.text.color: {menu_text}
osd.hilight.bg: flat solid
osd.hilight.bg.color: {blue}
osd.unhilight.bg: flat solid
osd.unhilight.bg.color: {sep}
"""

for name, pal in PALETTES.items():
    d = os.path.join(ROOT, f"FeatherOS-{name}", "openbox-3")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "themerc"), "w") as f:
        f.write(THEMERC.format(name=name, red=RED, yellow=YELLOW, green=GREEN,
                               blue=BLUE, red_d=DARKER[RED],
                               yellow_d=DARKER[YELLOW],
                               green_d=DARKER[GREEN], **pal))
    for button, g in BUTTONS.items():
        cname = button.replace("-", "_")
        with open(os.path.join(d, f"{button}.xbm"), "w") as f:
            f.write(xbm(cname, circle()))
        with open(os.path.join(d, f"{button}_hover.xbm"), "w") as f:
            f.write(xbm(cname + "_hover", cut(circle(), glyph(g))))
        with open(os.path.join(d, f"{button}_pressed.xbm"), "w") as f:
            f.write(xbm(cname + "_pressed", cut(circle(), glyph(g))))
print("wrote", ROOT)
